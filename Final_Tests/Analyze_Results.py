import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
import os

OUTPUT_DIR = Path("./patch_results")

# ==========================================
# 1. DATA LOADING
# ==========================================
def load_and_preprocess_data(component_name, metric_type, data_dir=OUTPUT_DIR):
    """Loads all CSVs for a given component and metric, concatenates them, and adds helpful columns."""
    search_pattern = f"*{component_name}*{metric_type}*.csv"
    csv_files = list(data_dir.rglob(search_pattern))

    if not csv_files:
        print(f"No files found for {component_name} {metric_type}")
        return None

    print(f"Found {len(csv_files)} files for {component_name} {metric_type}. Aggregating...")

    df_list = []
    for file in csv_files:
        temp_df = pd.read_csv(file)
        temp_df['Source_File'] = file.name
        # Extract a Read ID (Assuming your files are named like 'R4r0_mlp_...')
        temp_df['Read_ID'] = file.name.split('_')[0] 
        df_list.append(temp_df)
    
    df = pd.concat(df_list, ignore_index=True)

    # Boolean tracking for whether the text prediction completely flipped
    if 'Target_String_Prior' in df.columns and 'New_String' in df.columns:
        df['String_Flipped'] = df['Target_String_Prior'] != df['New_String']

    return df

# ==========================================
# 2. METRIC CALCULATIONS (AIE / ATE)
# ==========================================
def calculate_aie(df, score_column='Logit_Score'):
    """
    Calculates the Average Indirect Effect (AIE) by averaging the specified 
    score column across all reads for each intervention site (Layer + Time).
    """
    # Group by Layer and Time Offset, then average the score across all Read_IDs
    aie_df = df.groupby(['Layer', 'Time_Offset'])[score_column].mean().reset_index()
    aie_df.rename(columns={score_column: f'AIE_{score_column}'}, inplace=True)
    return aie_df

def calculate_max_scores(df):
    """Finds the maximum effect observed in each layer across all timesteps."""
    return df.groupby('Layer')[['Logit_Score', 'Posteriors_Score']].max().reset_index()

def calculate_flip_rates(df):
    """Calculates the percentage of runs where the decode string changed, per layer."""
    flip_rates = df.groupby('Layer')['String_Flipped'].mean().reset_index()
    flip_rates['String_Flipped'] *= 100
    return flip_rates

# ==========================================
# 3. PLOTTING FUNCTIONS
# ==========================================
def plot_aie_heatmap(aie_df, score_column, component_name, metric_type, plot_dir):
    """Plots the global AIE heatmap across all dataset reads."""
    heatmap_data = aie_df.pivot_table(index='Layer', columns='Time_Offset', values=f'AIE_{score_column}')
    
    plt.figure(figsize=(14, 8))
    sns.heatmap(heatmap_data, cmap="viridis", center=0)
    plt.title(f'Average Indirect Effect (AIE) Heatmap: {score_column}\n({component_name} | {metric_type})')
    plt.xlabel('Time Offset relative to window')
    plt.ylabel('Layer')
    plt.tight_layout()
    plt.savefig(plot_dir / f"aie_heatmap_{score_column.lower()}.png")
    plt.close()

def plot_aie_over_time(aie_df_logit, aie_df_post, component_name, metric_type, plot_dir):
    """Plots the AIE averaged over all layers for each time offset."""
    # Collapse layers to just see effect over time
    time_logit = aie_df_logit.groupby('Time_Offset')['AIE_Logit_Score'].mean().reset_index()
    time_post = aie_df_post.groupby('Time_Offset')['AIE_Posteriors_Score'].mean().reset_index()

    plt.figure(figsize=(12, 6))
    plt.plot(time_logit['Time_Offset'], time_logit['AIE_Logit_Score'], label='AIE Logit Score', color='blue', marker='o')
    plt.plot(time_post['Time_Offset'], time_post['AIE_Posteriors_Score'], label='AIE Posterior Score', color='orange', marker='s')
    
    plt.axvline(x=0, color='red', linestyle='--', label='Corruption Point / Center')
    
    plt.title(f'Average Indirect Effect (AIE) Over Time\n({component_name} | {metric_type})')
    plt.xlabel('Time Offset')
    plt.ylabel('Average Score across Dataset')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(plot_dir / "aie_over_time.png")
    plt.close()

def plot_bar_metrics(df, component_name, metric_type, plot_dir):
    """Generates bar charts for string flip percentages and max scores."""
    # String Flips
    flip_rates = calculate_flip_rates(df)
    plt.figure(figsize=(10, 6))
    sns.barplot(data=flip_rates, x='Layer', y='String_Flipped', color='teal')
    plt.title(f'String Flip % per Layer ({component_name} {metric_type})')
    plt.xlabel('Layer')
    plt.ylabel('% String Flipped')
    plt.savefig(plot_dir / "string_flip_bar_chart.png")
    plt.close()

    # Max Scores
    max_scores = calculate_max_scores(df)
    plt.figure(figsize=(10, 6))
    plt.plot(max_scores['Layer'], max_scores['Logit_Score'], label='Max Logit Score', marker='o')
    plt.plot(max_scores['Layer'], max_scores['Posteriors_Score'], label='Max Posterior Score', marker='s')
    plt.title(f'Max Score per Layer ({component_name} {metric_type})')
    plt.xlabel('Layer')
    plt.ylabel('Max Score')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.savefig(plot_dir / "max_scores_per_layer.png")
    plt.close()

# ==========================================
# 4. MAIN ORCHESTRATOR
# ==========================================
def analyze_component(component_name, metric_type):
    """Orchestrates data loading, calculation, and plotting."""
    
    # 1. Load Data
    df = load_and_preprocess_data(component_name, metric_type)
    if df is None:
        return

    # Create output directory
    plot_dir = OUTPUT_DIR / f"{component_name}_{metric_type}_aggregated_plots"
    plot_dir.mkdir(parents=True, exist_ok=True)

    # 2. Calculate AIE for both Logits and Posteriors
    aie_logits = calculate_aie(df, score_column='Logit_Score')
    aie_posteriors = calculate_aie(df, score_column='Posteriors_Score')

    # 3. Generate Plots
    plot_aie_heatmap(aie_logits, 'Logit_Score', component_name, metric_type, plot_dir)
    plot_aie_heatmap(aie_posteriors, 'Posteriors_Score', component_name, metric_type, plot_dir)
    
    plot_aie_over_time(aie_logits, aie_posteriors, component_name, metric_type, plot_dir)
    
    plot_bar_metrics(df, component_name, metric_type, plot_dir)

    print(f"✅ Analysis complete for {component_name} {metric_type}. Plots saved to {plot_dir}\n")

