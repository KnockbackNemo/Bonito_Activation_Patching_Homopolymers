OUTPUT_DIR = Path("./patch_results")

# ==========================================
# 1. DATA LOADING
# ==========================================
def load_and_preprocess_data(component_name, metric_type, data_dir=OUTPUT_DIR):
    """Loads all CSVs for a given component and metric, concatenates them, and adds helpful columns."""
    search_pattern = f"*{component_name}*{metric_type}*.csv"
    csv_files = list(data_dir.rglob(search_pattern))

    if not csv_files:
        print(f"No files found for {component_name} {metric_type}")
        return None

    print(f"Found {len(csv_files)} files for {component_name} {metric_type}. Aggregating...")

    df_list = []
    for file in csv_files:
        temp_df = pd.read_csv(file)
        temp_df['Source_File'] = file.name
        # Extract a Read ID (Assuming your files are named like 'R4r0_mlp_...')
        temp_df['Read_ID'] = file.name.split('_')[0] 
        df_list.append(temp_df)
    
    df = pd.concat(df_list, ignore_index=True)

    # Boolean tracking for whether the text prediction completely flipped
    if 'Target_String_Prior' in df.columns and 'New_String' in df.columns:
        df['String_Flipped'] = df['Target_String_Prior'] != df['New_String']

    return df

# ==========================================
# 2. METRIC CALCULATIONS (AIE / ATE)
# ==========================================
def calculate_aie(df, score_column='Logit_Score'):
    """
    Calculates the Average Indirect Effect (AIE) by averaging the specified 
    score column across all reads for each intervention site (Layer + Time).
    """
    # Group by Layer and Time Offset, then average the score across all Read_IDs
    aie_df = df.groupby(['Layer', 'Time_Offset'])[score_column].mean().reset_index()
    aie_df.rename(columns={score_column: f'AIE_{score_column}'}, inplace=True)
    return aie_df

def calculate_layerwise_aie(df, score_column='Logit_Score'):
    """
    Calculates the Layer-wise AIE regardless of exact timestep alignment.
    First takes the max score across time for each read, then averages those 
    max scores across all reads in the dataset.
    """
    # Step 1: Find the max effect for each layer within each individual read
    max_per_read = df.groupby(['Read_ID', 'Layer'])[score_column].max().reset_index()
    
    # Step 2: Average those max effects across all reads to get the Layer-wise AIE
    layerwise_aie = max_per_read.groupby('Layer')[score_column].mean().reset_index()
    layerwise_aie.rename(columns={score_column: f'Layerwise_AIE_{score_column}'}, inplace=True)
    
    return layerwise_aie

def calculate_max_scores(df):
    """Finds the maximum effect observed in each layer across all timesteps."""
    return df.groupby('Layer')[['Logit_Score', 'Posteriors_Score']].max().reset_index()

def calculate_flip_rates(df):
    """Calculates the percentage of runs where the decode string changed, per layer."""
    flip_rates = df.groupby('Layer')['String_Flipped'].mean().reset_index()
    flip_rates['String_Flipped'] *= 100
    return flip_rates

