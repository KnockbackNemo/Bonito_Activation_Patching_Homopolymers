def plot_aie_heatmap(aie_df, score_column, component_name, metric_type, plot_dir):
    heatmap_data = aie_df.pivot_table(index='Layer', columns='Time_Offset', values=f'AIE_{score_column}')
    numeric_heatmap = heatmap_data.apply(pd.to_numeric, errors='coerce') # Added float conversion fix
    plt.figure(figsize=(14, 8))
    sns.heatmap(numeric_heatmap, cmap="viridis", center=0)
    plt.title(f'Average Indirect Effect (AIE) Heatmap: {score_column}\n({component_name} | {metric_type})')
    plt.xlabel('Time Offset relative to window')
    plt.ylabel('Layer')
    plt.tight_layout()
    plt.savefig(plot_dir / f"aie_heatmap_{score_column.lower()}.png")
    plt.close()

def plot_layerwise_aie(layer_logit, layer_post, component_name, metric_type, plot_dir):
    merged = pd.merge(layer_logit, layer_post, on='Layer')
    plt.figure(figsize=(12, 6))
    x = np.arange(len(merged['Layer']))
    bar_width = 0.35
    plt.bar(x - bar_width/2, merged['Layerwise_AIE_Logit_Score'], bar_width, label='Logits', color='#1f77b4')
    plt.bar(x + bar_width/2, merged['Layerwise_AIE_Posteriors_Score'], bar_width, label='Posteriors', color='#ff7f0e')
    plt.title(f'Layer-wise Average Indirect Effect\n({component_name} | {metric_type})')
    plt.xlabel('Layer')
    plt.ylabel('Average Max Score Across Dataset')
    plt.xticks(x, merged['Layer'])
    plt.legend()
    plt.grid(axis='y', alpha=0.3)
    plt.tight_layout()
    plt.savefig(plot_dir / "layerwise_aie_discrete.png")
    plt.close()

def plot_combined_components(all_layer_data, metric_type, score_type='Logit_Score', plot_dir=OUTPUT_DIR):
    if not all_layer_data: return
    plt.figure(figsize=(12, 6))
    for component_name, df in all_layer_data.items():
        col_name = f'Layerwise_AIE_{score_type}'
        plt.plot(df['Layer'], df[col_name], label=component_name.upper(), marker='o', linewidth=2)
    plt.title(f'Combined Components Layer-wise AIE: {score_type}\n({metric_type})')
    plt.xlabel('Layer')
    plt.ylabel('Average Max Score Across Dataset')
    sample_df = list(all_layer_data.values())[0]
    plt.xticks(sample_df['Layer'])
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plot_dir.mkdir(parents=True, exist_ok=True)
    plt.savefig(plot_dir / f"combined_layerwise_{score_type.lower()}_{metric_type}.png")
    plt.close()

def plot_aie_over_time(aie_df_logit, aie_df_post, component_name, metric_type, plot_dir):
    time_logit = aie_df_logit.groupby('Time_Offset')['AIE_Logit_Score'].mean().reset_index()
    time_post = aie_df_post.groupby('Time_Offset')['AIE_Posteriors_Score'].mean().reset_index()
    plt.figure(figsize=(12, 6))
    plt.plot(time_logit['Time_Offset'], time_logit['AIE_Logit_Score'], label='AIE Logit Score', color='blue', marker='o')
    plt.plot(time_post['Time_Offset'], time_post['AIE_Posteriors_Score'], label='AIE Posterior Score', color='orange', marker='s')
    plt.axvline(x=0, color='red', linestyle='--', label='Corruption Point / Center')
    plt.title(f'Average Indirect Effect (AIE) Over Time\n({component_name} | {metric_type})')
    plt.xlabel('Time Offset')
    plt.ylabel('Average Score across Dataset')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(plot_dir / "aie_over_time.png")
    plt.close()

def plot_bar_metrics(df, component_name, metric_type, plot_dir):
    flip_rates = calculate_flip_rates(df)
    plt.figure(figsize=(10, 6))
    sns.barplot(data=flip_rates, x='Layer', y='String_Flipped', color='teal')
    plt.title(f'String Flip % per Layer ({component_name} {metric_type})')
    plt.xlabel('Layer')
    plt.ylabel('% String Flipped')
    plt.savefig(plot_dir / "string_flip_bar_chart.png")
    plt.close()

