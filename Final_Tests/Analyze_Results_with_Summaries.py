def generate_summary_report(df, layer_logit, layer_post, component_name, metric_type, plot_dir):
    """Generates a text summary analyzing the dataset used and the aggregated impact scores."""
    report_path = plot_dir / f"summary_report_{component_name}_{metric_type}.txt"
    
    with open(report_path, "w") as f:
        f.write(f"=== AGGREGATED SUMMARY REPORT: {component_name.upper()} ({metric_type.upper()}) ===\n")
        f.write("-" * 65 + "\n\n")
        
        # --- 1. IMPACT ANALYSIS ---
        f.write("1. IMPACT ANALYSIS\n")
        
        # Max Logit AIE
        max_logit_row = layer_logit.loc[layer_logit['Layerwise_AIE_Logit_Score'].idxmax()]
        f.write(f"  - Max Average Logit Impact: Layer {int(max_logit_row['Layer'])} "
                f"(Score: {max_logit_row['Layerwise_AIE_Logit_Score']:.4f})\n")
        
        # Max Posteriors AIE
        max_post_row = layer_post.loc[layer_post['Layerwise_AIE_Posteriors_Score'].idxmax()]
        f.write(f"  - Max Average Posteriors Impact: Layer {int(max_post_row['Layer'])} "
                f"(Score: {max_post_row['Layerwise_AIE_Posteriors_Score']:.4f})\n")
        
        # String Flips
        flip_rates = calculate_flip_rates(df)
        if not flip_rates.empty and flip_rates['String_Flipped'].max() > 0:
            max_flip_row = flip_rates.loc[flip_rates['String_Flipped'].idxmax()]
            f.write(f"  - Highest String Flip Rate: Layer {int(max_flip_row['Layer'])} "
                    f"({max_flip_row['String_Flipped']:.1f}% of reads flipped)\n")
        f.write("\n")

        # --- 2. DATASET ANALYSIS ---
        f.write("2. DATASET PROFILE\n")
        unique_reads = df['Read_ID'].nunique()
        f.write(f"  - Total Individual Runs Analyzed: {unique_reads}\n")
        
        if 'Read_Num' in df.columns:
            read_origins = df.groupby('Read_Num')['Read_ID'].nunique()
            f.write("  - Origin Reads Used:\n")
            for read_num, count in read_origins.items():
                f.write(f"      * Read {read_num}: {count} run(s)\n")
        
        if 'Error_Type' in df.columns and len(df[df['Error_Type'] != 'Unknown']) > 0:
            f.write("\n  - Error Types Distributed:\n")
            # Get one row per unique run
            run_metadata = df.drop_duplicates(subset=['Read_ID'])
            error_counts = run_metadata['Error_Type'].value_counts()
            for err_type, count in error_counts.items():
                f.write(f"      * {err_type}: {count} run(s)\n")
                
            f.write("\n  - Clean Homopolymer Lengths:\n")
            length_counts = run_metadata['Clean_Length'].value_counts()
            for length, count in length_counts.items():
                f.write(f"      * Length {length}: {count} run(s)\n")
                
            f.write("\n  - Base Letters Targeted:\n")
            base_counts = run_metadata['Base_Letter'].value_counts()
            for base, count in base_counts.items():
                f.write(f"      * {base}: {count} run(s)\n")
        else:
            f.write("\n  - (Input metadata CSVs not found. Unable to profile error types and lengths.)\n")

        f.write("\n" + "="*65 + "\n")
    print(f"📄 Summary report saved to {report_path.name}")

