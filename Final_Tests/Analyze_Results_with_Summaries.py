def load_and_preprocess_data(component_name, metric_type, data_dir=OUTPUT_DIR):
    """Loads all CSVs for a given component and metric, concatenates them, and adds helpful columns."""
    search_pattern = f"*{component_name}*{metric_type}*.csv"
    csv_files = list(data_dir.rglob(search_pattern))

    if not csv_files:
        print(f"No files found for {component_name} {metric_type}")
        return None

    print(f"Found {len(csv_files)} files for {component_name} {metric_type}. Aggregating...")

    df_list = []
    
    # Dictionary to cache input metadata CSVs so we only load them once
    input_metadata_cache = {}

    for file in csv_files:
        temp_df = pd.read_csv(file)
        temp_df['Source_File'] = file.name
        
        # Ensure scores are floats immediately
        if temp_df.empty:
            continue
            
        temp_df['Logit_Score'] = pd.to_numeric(temp_df['Logit_Score'], errors='coerce')
        temp_df['Posteriors_Score'] = pd.to_numeric(temp_df['Posteriors_Score'], errors='coerce')

        # Extract Read and Run indices from filename (e.g., "R4r0_...")
        match = re.search(r'R(\d+)r(\d+)', file.name)
        if match:
            read_num = match.group(1)
            run_num = int(match.group(2))
            temp_df['Read_Num'] = read_num
            temp_df['Run_Num'] = run_num
            temp_df['Read_ID'] = f"R{read_num}r{run_num}"

            # Try to fetch metadata for this specific run
            if read_num not in input_metadata_cache:
                # Search for the Input Gen CSV in the current dir or output dir
                if RUN_CONTROL:
                    possible_paths = [Path(f"./data/controls/Negative_Control_results_read_{read_num}.csv")]
                else: 
                    possible_paths = [Path(f"./data/pairs/Input_gen_results_read_{read_num}.csv")]

                meta_df = None
                for p in possible_paths:
                    if p.exists():
                        meta_df = pd.read_csv(p)
                        break
                input_metadata_cache[read_num] = meta_df

            # Merge metadata if found
            meta_df = input_metadata_cache[read_num]
            if meta_df is not None and run_num < len(meta_df):
                row = meta_df.iloc[run_num]
                temp_df['Error_Type'] = row.get('Type', 'Unknown')
                temp_df['Clean_Length'] = row.get('Clean H-er Length', 'Unknown')
                temp_df['Corrupt_Length'] = row.get('Corrupt H-er Length', 'Unknown')
                temp_df['Base_Letter'] = row.get('Base Letter', 'Unknown')
            else:
                temp_df['Error_Type'] = 'Unknown'
                temp_df['Clean_Length'] = 'Unknown'
                temp_df['Corrupt_Length'] = 'Unknown'
                temp_df['Base_Letter'] = 'Unknown'
        else:
            temp_df['Read_ID'] = file.name.split('_')[0] 
            temp_df['Error_Type'] = 'Unknown'
            temp_df['Clean_Length'] = 'Unknown'
            
        df_list.append(temp_df)
    
    df = pd.concat(df_list, ignore_index=True)

    # Boolean tracking for whether the text prediction completely flipped
    if 'Target_String_Prior' in df.columns and 'New_String' in df.columns:
        df['String_Flipped'] = df['Target_String_Prior'] != df['New_String']

    return df

